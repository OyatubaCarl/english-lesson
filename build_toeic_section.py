def gloss_for(word: str) -> str:
    """与えられた英単語の日本語訳を返す（小文字化＆記号除去で照合）。"""
    bare = re.sub(r"[^\w']", "", word).lower()
    if not bare:
        return ""
    if bare in GLOSS:
        return GLOSS[bare]
    # 単純な複数形/過去形変化を試行
    for suf in ("ies", "es", "s", "ed", "ing", "er", "est"):
        if bare.endswith(suf) and len(bare) > len(suf) + 2:
            base = bare[: -len(suf)]
            if base in GLOSS:
                return GLOSS[base]
            if suf == "ies" and (base + "y") in GLOSS:
                return GLOSS[base + "y"]
    return ""


