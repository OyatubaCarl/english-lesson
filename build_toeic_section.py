def esc(s: str) -> str:
    return (
        s.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def render_jp_paragraph(segs: list) -> str:
    """jp混じり段落をHTMLに変換。"""
    out = ["<p>"]
    for seg in segs:
        if isinstance(seg, str):
            out.append(esc(seg))
        else:
            base = seg["base"]
            ipa = seg.get("ipa", "")
            ja = seg.get("ja", "")
            pos = seg.get("pos", "noun")
            out.append(
                f'<span class="w" data-base="{esc(base)}" data-ipa="{esc(ipa)}" data-ja="{esc(ja)}" data-pos="{esc(pos)}">{esc(base)}</span>'
            )
    out.append("</p>")
    return "".join(out)


def tokenize_en(text: str) -> list[tuple[str, str | None]]:
    """英文を単語と区切りに分解。
    返り値: [(token, type), ...]  type は 'word' or 'sep'
    """
    out = []
    parts = re.split(r"(\s+|[.,;:!?\"'\(\)\-—–]+)", text)
    for p in parts:
        if not p:
            continue
        if re.match(r"^\s+$", p):
            out.append((p, "ws"))
        elif re.match(r"^[.,;:!?\"'\(\)\-—–]+$", p):
            out.append((p, "punct"))
        else:
            out.append((p, "word"))
    return out


def render_en_paragraph(text: str) -> str:
    """英文段落をper-word span に変換。"""
    out = ["<p>"]
    for tok, kind in tokenize_en(text):
        if kind == "word":
            base = re.sub(r"[^\w']", "", tok).lower() or tok.lower()
            ja = gloss_for(tok)
            out.append(f'<span class="we" data-base="{esc(base)}" data-ja="{esc(ja)}">{esc(tok)}</span>')
        else:
            out.append(esc(tok))
    out.append("</p>")
    return "".join(out)


def render_jp_full_paragraph(text: str) -> str:
    return f"<p>{esc(text)}</p>"


def render_examples(examples: list[tuple[str, str]]) -> str:
    lis = []
    for en, ja in examples:
        lis.append(f'          <li><em>{esc(en)}</em> <span class="ja">― {esc(ja)}</span></li>')
    return "\n".join(lis)


