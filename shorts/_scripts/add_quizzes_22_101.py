def split_subtitles(sentence: str, word: str) -> list[dict]:
    """body_narration を句読点と英単語で分割して、上から下に並ぶ body_subtitles を生成。
    y軸は中央〜下: 820 から 120px刻みで増やす。"""
    # 英単語と日本語パートに分割
    parts = sentence.split(word)
    rows: list[str] = []
    for i, p in enumerate(parts):
        p = p.strip()
        if p:
            # 句読点で更に分割 (読点・句点)
            chunks = re.split(r"(?<=、)|(?<=。)", p)
            for c in chunks:
                c = c.strip()
                if c:
                    rows.append(("jp", c))
        if i < len(parts) - 1:
            rows.append(("en", word))
    # 連続する短い jp は結合する (1行15字以内なら結合)
    merged: list[tuple] = []
    for lang, text in rows:
        if merged and merged[-1][0] == "jp" == lang and len(merged[-1][1]) + len(text) <= 15:
            merged[-1] = ("jp", merged[-1][1] + text)
        else:
            merged.append((lang, text))
    # y軸配置
    y = 820
    subs = []
    step = 120
    for lang, text in merged:
        item = {"text": text, "y": y}
        if lang == "en":
            item["style"] = "BodyEN"
        subs.append(item)
        y += step
    return subs


def rebalance_correct_index(items: list, group: str) -> None:
    """各グループ40件の正解位置を A/B/C/D 均等 (各10) になるよう再シャッフル。
    変更は items を破壊的に。"""
    # 40件を10ずつA/B/C/Dに割り振る
    indices = list(range(len(items)))
    random.shuffle(indices)
    target = [0]*10 + [1]*10 + [2]*10 + [3]*10
    random.shuffle(target)
    for i, t in zip(indices, target):
        items[i] = list(items[i])
        # choices の元の正解単語を新位置に
        items[i][5] = t  # correct_index in tuple position
        items[i] = tuple(items[i])


def main():
    data = json.loads(QPATH.read_text(encoding="utf-8"))

    # group別に分けてリバランス
    hard = [item for item in DATA if item[7] == "hard"]
    easy = [item for item in DATA if item[7] == "easy"]

    # 正解位置リバランス: 元の正解選択肢を保持しつつ、位置を変える
    def assign_targets(group_items: list) -> list:
        # 40件に A/B/C/D を10ずつ均等割
        n = len(group_items)
        per = n // 4
        targets = [0]*per + [1]*per + [2]*per + [3]*per
        # 残りを A から
        for i in range(n - len(targets)):
            targets.append(i % 4)
        random.shuffle(targets)
        # 各itemの correct を新位置に置く
        out = []
        for item, new_idx in zip(group_items, targets):
            qid, word, meaning, sentence, choices, old_idx, bg, group = item
            correct_label = choices[old_idx]
            new_choices = choices[:]
            # 元の位置から外す
            new_choices.pop(old_idx)
            # 新しい位置に挿入
            new_choices.insert(new_idx, correct_label)
            out.append((qid, word, meaning, sentence, new_choices, new_idx, bg, group))
        return out

    hard_rebalanced = assign_targets(hard)
    easy_rebalanced = assign_targets(easy)

    for items in (hard_rebalanced, easy_rebalanced):
        for item in items:
            qid, word, meaning, sentence, choices, correct_idx, bg, group = item
            q = {
                "id": qid,
                "word": word,
                "meaning_jp": meaning,
                "body_subtitles": split_subtitles(sentence, word),
                "body_narration": sentence,
                "choices": choices,
                "correct_index": correct_idx,
                "bg_filename": f"bg_{qid}.png",
                "bg_prompt": bg,
            }
            data.append(q)

    QPATH.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n",
                     encoding="utf-8")

    # 正解位置の分布を確認
    from collections import Counter
    new_items = [d for d in data if d["id"] in {x[0] for x in DATA}]
    print(f"added {len(new_items)} quizzes")
    hard_dist = Counter("ABCD"[d["correct_index"]] for d in new_items
                        if d["id"] in {x[0] for x in hard})
    easy_dist = Counter("ABCD"[d["correct_index"]] for d in new_items
                        if d["id"] in {x[0] for x in easy})
    print(f"hard distribution: {dict(hard_dist)}")
    print(f"easy distribution: {dict(easy_dist)}")


if __name__ == "__main__":
    main()
