"""chunk_1 のruby audit結果JSON生成スクリプト"""
import json

INPUT = '_ruby_audit/chunk_1.json'
OUTPUT = '_ruby_audit/result_1.json'

with open(INPUT, encoding='utf-8') as f:
    data = json.load(f)

items_by_id = {it['id']: it for it in data}

results = []


def add(it_id, severity, issue_type, fragment, context, correct, comment):
    it = items_by_id[it_id]
    results.append({
        'id': it_id,
        'word': it['word'],
        'severity': severity,
        'issue_type': issue_type,
        'fragment': fragment,
        'context': context,
        'correct': correct,
        'comment': comment,
    })


