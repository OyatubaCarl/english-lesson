# === ソート ===
def sort_key(r):
    sev_order = {'bad': 0, 'warn': 1}
    return (sev_order.get(r['severity'], 2), r['id'])

results.sort(key=sort_key)

with open(OUTPUT, 'w', encoding='utf-8') as f:
    json.dump(results, f, ensure_ascii=False, indent=2)

# 集計
