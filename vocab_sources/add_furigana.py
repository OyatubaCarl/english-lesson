def has_kanji(s: str) -> bool:
    return bool(KANJI.search(s))


def kata_to_hira(s: str) -> str:
    return "".join(chr(ord(c) - 0x60) if "ァ" <= c <= "ヶ" else c for c in s)


def chunk_to_aozora(orig: str, hira: str) -> str:
    """pykakasi チャンクを青空ルビに。混在語は｜形式。"""
    if not has_kanji(orig):
        return orig
    if not hira:
        return orig
    o, h = orig, hira
    on = kata_to_hira(o)  # 比較用に正規化
    # 共通サフィックス(かな部分のみ)
    suf = 0
    while suf < min(len(o), len(h)) and on[len(o)-1-suf] == h[len(h)-1-suf] and not has_kanji(o[len(o)-1-suf]):
        suf += 1
    # 共通プレフィックス
    pre = 0
    while pre < min(len(o), len(h)) - suf and on[pre] == h[pre] and not has_kanji(o[pre]):
        pre += 1
    base = o[pre:len(o)-suf] if suf else o[pre:]
    rt = h[pre:len(h)-suf] if suf else h[pre:]
    if not base or not rt:
        return orig
    suffix = o[len(o)-suf:] if suf else ""
    prefix = o[:pre]
    # base に かな が混ざる(我が家・持ち主 等)→ ｜形式
    if re.search(r"[ぁ-んァ-ヶー]", base):
        return prefix + "｜" + base + f"《{rt}》" + suffix
    return prefix + base + f"《{rt}》" + suffix


def to_aozora(text: str) -> str:
    embeds: list[str] = []
    def stash_embed(m):
        embeds.append(m.group(0))
        return f"⟦E{len(embeds)-1}⟧"
    text = re.sub(r"<[^>]+>", stash_embed, text)

    protected: list[str] = []

    # 数字+助数詞を保護
    for counter, reading in COUNTERS:
        def repl_counter(m, c=counter, r=reading):
            protected.append(f"{m.group(1)}{c}《{r}》")
            return f"⟦P{len(protected)-1}⟧"
        text = re.sub(r"(\d+)" + re.escape(counter), repl_counter, text)

    # OVERRIDES(正規表現)を保護。
    # パターンの長さ降順で適用して「通勤客」を「通勤」より先にマッチさせる
    for pat, repl in sorted(OVERRIDES, key=lambda x: -len(x[0])):
        def repl_override(m, r=repl):
            protected.append(m.expand(r))
            return f"⟦P{len(protected)-1}⟧"
        text = re.sub(pat, repl_override, text)

    out = []
    for item in kks.convert(text):
        out.append(chunk_to_aozora(item["orig"], item["hira"]))
    text = "".join(out)

    for i in range(len(protected) - 1, -1, -1):
        text = text.replace(f"⟦P{i}⟧", protected[i])
    for i in range(len(embeds) - 1, -1, -1):
        text = text.replace(f"⟦E{i}⟧", embeds[i])
    return text


RUBY_TOKEN = re.compile(r"(?:｜([^《》｜]+)|([一-龯々〆ヶ]+))《([^》]+)》")


def aozora_to_kana(aozora: str) -> str:
    """青空ルビ → 読み上げテキスト(逐次パース)。
    数字+助数詞は漢字のまま残す(say が連濁込みで正読する)。"""
    out = []
    last = 0
    for m in RUBY_TOKEN.finditer(aozora):
        out.append(aozora[last:m.start()])
        base = m.group(1) or m.group(2)
        rt = m.group(3)
        prev = aozora[m.start()-1] if m.start() > 0 else ""
        if prev.isdigit() and base in COUNTER_SET:
            out.append(base)          # 30分 → 30分 (say任せ)
        else:
            out.append(rt)
        last = m.end()
    out.append(aozora[last:])
    s = "".join(out)
    # <word> はタグのまま保持(後段で日本語TTSと英語TTSを切り替えるため)
    return s


def strip_ruby(aozora: str) -> str:
    """ルビ記号を除いた素のテキスト(検証用)."""
    s = RUBY_TOKEN.sub(lambda m: (m.group(1) or m.group(2)), aozora)
    return s


def main() -> None:
    parser = argparse.ArgumentParser(description="WordTacos クイズJSONに青空ルビを付与")
    parser.add_argument(
        "src",
        nargs="?",
        default=str(DEFAULT_SRC),
        help="対象クイズJSONファイル (デフォルト: stage1_quizzes_clean.json)",
    )
    args = parser.parse_args()
    src = Path(args.src)
    if not src.is_absolute():
        src = Path(__file__).parent / args.src
    if not src.exists():
        print(f"ERROR: ファイルが見つかりません: {src}", file=sys.stderr)
        sys.exit(1)
    print(f"対象: {src}")
    data = json.loads(src.read_text(encoding="utf-8"))

    leftover = []
    roundtrip_ng = []
    for q in data["quizzes"]:
        q["body_ruby"] = to_aozora(q["body"])
        q["choices_ruby"] = [to_aozora(c) for c in q["choices"]]
        q["explanation_ruby"] = to_aozora(q.get("explanation", ""))
        q["body_kana"] = aozora_to_kana(q["body_ruby"])

        # 検証1: ルビ除去 → 元テキストと一致するか
        if strip_ruby(q["body_ruby"]) != q["body"]:
            roundtrip_ng.append((q["word"], q["body"], strip_ruby(q["body_ruby"])))

        # 検証2: ルビ後に裸の漢字が残っていないか
        no_ruby = RUBY_TOKEN.sub("", q["body_ruby"])
        no_ruby = re.sub(r"<[^>]+>", "", no_ruby)
        if has_kanji(no_ruby):
            leftover.append((q["word"], q["body_ruby"], no_ruby))

    src.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"完了: {len(data['quizzes'])}問")
    print(f"往復不一致: {len(roundtrip_ng)}")
    for w, orig, rt in roundtrip_ng[:5]:
        print(f"  [{w}]\n    orig: {orig}\n    strip: {rt}")
    print(f"裸の漢字残: {len(leftover)}")
    for w, b, nk in leftover[:8]:
        kanji_only = "".join(c for c in nk if KANJI.match(c))
        print(f"  [{w}] 残: {kanji_only}")

    print("\n=== 重点サンプル ===")
    targets = ["always", "Friday", "stand", "leave", "want", "car", "wall", "animal"]
    qs = {q["word"]: q for q in data["quizzes"]}
    for w in targets:
        if w in qs:
            print(f"\n  ● {w}")
            print(f"    ruby: {qs[w]['body_ruby']}")
            print(f"    kana: {qs[w]['body_kana']}")


if __name__ == "__main__":
    main()
